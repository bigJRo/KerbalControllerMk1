#!/usr/bin/env python3
"""Generate sim_font.h: a 5x7 glyph table (ASCII 32..126) in the Adafruit
classic-font layout (5 column bytes per glyph, bit 0 = top row), rendered from
DejaVu Sans Mono. Only used to draw readable text into the simulated TFT."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
out = sys.argv[1]
font = ImageFont.truetype(FONT, 9)
rows = []
for code in range(32, 127):
    img = Image.new("L", (12, 14), 0)
    d = ImageDraw.Draw(img)
    d.text((0, -2), chr(code), font=font, fill=255)
    bbox = img.getbbox()
    cols = []
    # place the glyph in a 5x7 box: crop horizontally around the ink, scale if wider
    if bbox:
        x0 = max(0, min(bbox[0], 12 - 5))
        w = bbox[2] - bbox[0]
        if w > 5:
            img = img.crop((bbox[0], 0, bbox[2], 14)).resize((5, 14))
            x0 = 0
        for x in range(5):
            b = 0
            for y in range(7):
                if img.getpixel((x0 + x, y + 1)) > 110:
                    b |= 1 << y
            cols.append(b)
    else:
        cols = [0] * 5
    rows.append(cols)
with open(out, "w") as f:
    f.write("// generated by make_font.py\n#pragma once\nstatic const unsigned char SIM_FONT[95][5] = {\n")
    for cols in rows:
        f.write("  {" + ",".join("0x%02X" % c for c in cols) + "},\n")
    f.write("};\n")
